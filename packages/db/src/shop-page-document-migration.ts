import { BOOKING_SECTIONS, HERO_SECTION, LEGACY_SECTION_DOCS, LEGACY_SECTION_IDS, presetOf, sectionKey, TRADE_PRESETS, type DocSection } from "@akinaza/core";

/**
 * Migration 0038 (akinaza#400): the shop page as a document, versioned. Its data step turns every existing `shop_page` row into a published v1,
 * from the SAME table the pure function `documentFromLegacy` reads (`LEGACY_SECTION_DOCS`): `shop-page-document.test.ts` compares the two.
 * `pnpm --filter @akinaza/db exec tsx src/gen-shop-page-document-migration.ts > drizzle/0038_shop_page_document.sql`
 */
const lit = (value: unknown) => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
const doc = (key: string, d: DocSection) => ({ key, ...d });

const mapRows = LEGACY_SECTION_IDS.flatMap((legacy) => {
  const docs = LEGACY_SECTION_DOCS[legacy];
  return docs.map((d, rank) => `    ('${legacy}', ${rank}, ${lit(doc(sectionKey(legacy, rank, docs.length), d))})`);
});
const presetRows = (Object.keys(TRADE_PRESETS) as (keyof typeof TRADE_PRESETS)[]).map((trade) => `    ('${trade}', ${lit(presetOf(trade))})`);

export const SHOP_PAGE_DOCUMENT_MIGRATION_SQL = `-- The shop page as a document (akinaza#400): draft and published, versioned, audited. Generated by shop-page-document-migration.ts; never edit by hand.
CREATE TABLE shop_page_versions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  shop_id uuid NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
  version integer NOT NULL CHECK (version >= 1),
  status text NOT NULL CHECK (status IN ('draft','published','archived')),
  schema integer NOT NULL CHECK (schema >= 1),
  doc jsonb NOT NULL CHECK (jsonb_typeof(doc) = 'object'),
  author_id uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz,
  CONSTRAINT shop_page_versions_published CHECK ((status = 'draft') = (published_at IS NULL)),
  UNIQUE (shop_id, version)
);
-- One draft and one published document per shop: the published one IS the page.
CREATE UNIQUE INDEX shop_page_versions_one_draft ON shop_page_versions (shop_id) WHERE status = 'draft';
CREATE UNIQUE INDEX shop_page_versions_one_published ON shop_page_versions (shop_id) WHERE status = 'published';

-- Every existing page becomes the document it already is: the same sections in the same order, a hidden one disabled.
INSERT INTO shop_page_versions (shop_id, version, status, schema, doc, published_at)
SELECT sp.shop_id, 1, 'published', 1,
  jsonb_build_object(
    'schema', 1,
    'preset', (SELECT p.preset FROM (VALUES
${presetRows.join(",\n")}
    ) AS p(trade, preset) WHERE p.trade = COALESCE(sp.shop_type, CASE s.business_type WHEN 'pets' THEN 'pets' ELSE 'consulting' END)),
    'sections', jsonb_build_array(${lit(doc("s_hero", HERO_SECTION))})
      || COALESCE((
        SELECT jsonb_agg(m.doc || CASE WHEN l.visible THEN '{}'::jsonb ELSE '{"disabled":true}'::jsonb END ORDER BY l.ord, m.rank)
        FROM (
          SELECT e.value ->> 'id' AS id, (e.value ->> 'visible')::boolean AS visible, e.ord::numeric AS ord
          FROM jsonb_array_elements(sp.sections) WITH ORDINALITY AS e(value, ord)
          UNION ALL
          -- a list that predates trust reads it right before the gallery (the end without one)
          SELECT 'trust', true, COALESCE((SELECT g.ord FROM jsonb_array_elements(sp.sections) WITH ORDINALITY AS g(value, ord) WHERE g.value ->> 'id' = 'gallery'), 1000000) - 0.5
          WHERE NOT EXISTS (SELECT 1 FROM jsonb_array_elements(sp.sections) AS t(value) WHERE t.value ->> 'id' = 'trust')
        ) AS l
        JOIN (VALUES
${mapRows.join(",\n")}
        ) AS m(id, rank, doc) ON m.id = l.id
      ), '[]'::jsonb)
      || ${lit(BOOKING_SECTIONS.map((d) => doc(`s_booking_${d.variant}`, d)))}
  ),
  now()
FROM shop_page sp
JOIN shops s ON s.id = sp.shop_id;
`;
